#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn release_file_names_and_display_title_share_one_version() {
        assert!(WINDOWS_CLIENT_TITLE.contains(WINDOWS_APP_VERSION));
        assert!(SYNC_LAUNCHER_FILE_NAME.contains(WINDOWS_APP_VERSION));
        assert!(SYNC_SERVER_FILE_NAME.contains(WINDOWS_APP_VERSION));
        assert_eq!("gridtimer", PRODUCT.internal_id);
    }

    #[test]
    fn platform_release_versions_remain_independent() {
        #[cfg(target_os = "android")]
        {
            let android_build = include_str!("../../../app/build.gradle");
            assert!(android_build.contains(&format!("versionName '{}'", ANDROID_APP_VERSION)));
            assert!(android_build.contains(&format!("versionCode {}", ANDROID_VERSION_CODE)));
            assert_eq!(ANDROID_APP_VERSION, PRODUCT.app_version);
        }
        #[cfg(not(target_os = "android"))]
        {
            assert_eq!(WINDOWS_APP_VERSION, PRODUCT.app_version);
            assert_ne!(WINDOWS_APP_VERSION, ANDROID_APP_VERSION);
        }
    }
}
